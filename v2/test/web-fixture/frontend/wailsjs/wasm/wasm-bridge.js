/* The toolchain exec joins first: it defines globalThis.Go (the version of
   wasm_exec.js asserted by `wails generate webbindings` to match the Go
   compiler used for the backend module). */
import './go-exec.js';

const Go = globalThis.Go;

const state = {
    started: false,          // loadAndRunWasm() launched
    failed: false,
    pendingMessages: [],     // window.WailsInvoke traffic before the module is ready
    pendingException: null,  // first boot failure, for formatted diagnostics
};

/* ------------------------------------------------------------------ URL */

function candidateUrls() {
    const override = new URLSearchParams(document.location.search).get('wasmUrl');
    if (override) {
        // The app wins: an explicit override bypasses every other candidate.
        return [override];
    }
    const base = new URL('.', document.baseURI).href.replace(/\/$/, '');
    return [
        `${base}/wasm/app.wasm`,
        `${base}/wasm/main.wasm`,
    ];
}

/* ------------------------------------------------------------------ boot */

async function loadAndRunWasm() {
    const candidates = candidateUrls();
    let lastError = null;

    for (const url of candidates) {
        let response;
        try {
            response = await fetch(url, { cache: 'force-cache' });
        } catch (err) {
            lastError = err;
            continue;
        }
        if (!response.ok) {
            lastError = new Error(`HTTP ${response.status} for ${url}`);
            continue;
        }

        let instance;
        try {
            const go = new Go();
            const contentType = response.headers.get('content-type') || '';
            if (contentType.includes('application/wasm')) {
                ({ instance } = await WebAssembly.instantiateStreaming(response, go.importObject));
            } else {
                // Wrong MIME (static hosts): buffered compile fallback.
                const bytes = await response.arrayBuffer();
                ({ instance } = await WebAssembly.instantiate(bytes, go.importObject));
            }
        } catch (err) {
            lastError = err;
            continue;
        }

        try {
            state.started = true;
            flushPendingMessages();
            await go.run(instance);
            // main() returning kills the bridge; report loudly.
            console.error('[wails] WASM backend has stopped (main returned). Bridge disabled.');
        } catch (err) {
            console.error('[wails] WASM backend crashed:', err);
        }
        return;
    }

    state.failed = true;
    state.pendingException = lastError;
    console.error(`[wails] unable to load the WASM backend (tried ${candidates.join(', ')}):`, lastError);
    rejectPendingMessages();
}

/* ------------------------------------------------------------------ seam */

function dispatchToGo(message) {
    const fn = globalThis.__wailsWasmDispatch;
    if (typeof fn !== 'function') {
        // Go has not installed the handler yet (boot or generation mode).
        state.pendingMessages.push(message);
        return;
    }
    fn(message);
}

function flushPendingMessages() {
    const messages = state.pendingMessages;
    state.pendingMessages = [];
    for (const message of messages) {
        dispatchToGo(message);
    }
    // DOM ready may have lain in wait while the module was booting.
    requestDomReady();
}

function rejectPendingMessages() {
    // Nothing can answer these anymore; drop them with a console note.
    const count = state.pendingMessages.length;
    state.pendingMessages = [];
    if (count > 0) {
        console.warn(`[wails] dropped ${count} buffered runtime message(s) after a failed WASM boot.`);
    }
}

window.WailsInvoke = function WailsInvoke(message) {
    if (typeof message !== 'string' || message.length === 0) return;
    dispatchToGo(message);
};

/* --------------------------------------------------------------- domready */

function requestDomReady() {
    // Tell Go the DOM is ready. Deferred if the handler is not installed
    // yet, so the WASM boot order never blocks the lifecycle hooks.
    const fn = globalThis.__wailsWasmDomReady;
    if (typeof fn === 'function') {
        fn();
        return;
    }
    // Not installed yet (module still downloading): flag it, Go consumes
    // the flag inside install().
    globalThis.__wailsWasmDomReadyRequested = true;
}

if (typeof document !== 'undefined') {
    if (document.readyState === 'loading') {
        document.addEventListener('DOMContentLoaded', requestDomReady);
    } else if (document.readyState === 'interactive' || document.readyState === 'complete') {
        // Module scripts are deferred — they evaluate with the DOM parsed.
        requestDomReady();
    }
}

/* ---------------------------------------------------------------- start */

if (typeof document !== 'undefined') {
    loadAndRunWasm();
}

export { loadAndRunWasm, dispatchToGo, candidateUrls, requestDomReady };
